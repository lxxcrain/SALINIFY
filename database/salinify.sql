-- USER ACCOUNTS AND LEARNING PROGRESS TABLES

-- USERS
-- Stores registered Salinify accounts

CREATE TABLE IF NOT EXISTS users (
    user_id INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    username VARCHAR(50) NOT NULL UNIQUE,
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);


-- 2. QUIZ ATTEMPTS
-- Stores every completed quiz and its score

CREATE TABLE IF NOT EXISTS quiz_attempts (
    attempt_id INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,

    user_id INTEGER NOT NULL
        REFERENCES users(user_id) ON DELETE CASCADE,

    quiz_id INTEGER NOT NULL
        REFERENCES quizzes(quiz_id) ON DELETE RESTRICT,

    score INTEGER NOT NULL DEFAULT 0
        CHECK (score >= 0),

    total_questions INTEGER NOT NULL
        CHECK (total_questions > 0),

    started_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    completed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CHECK (score <= total_questions)
);


-- 3. QUIZ ANSWER DETAILS
-- Stores answers for each question in an attempt
-- word_id links a question to a word when applicable

CREATE TABLE IF NOT EXISTS quiz_answer_details (
    answer_id INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,

    attempt_id INTEGER NOT NULL
        REFERENCES quiz_attempts(attempt_id) ON DELETE CASCADE,

    question_id INTEGER NOT NULL
        REFERENCES questions(question_id) ON DELETE RESTRICT,

    selected_option_id INTEGER
        REFERENCES options(option_id) ON DELETE SET NULL,

    word_id INTEGER
        REFERENCES words(word_id) ON DELETE SET NULL,

    is_correct BOOLEAN NOT NULL,

    answered_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    UNIQUE (attempt_id, question_id)
);


-- 4. USER WORD PROGRESS
-- Tracks each user's progress for each word

CREATE TABLE IF NOT EXISTS user_word_progress (
    progress_id INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,

    user_id INTEGER NOT NULL
        REFERENCES users(user_id) ON DELETE CASCADE,

    word_id INTEGER NOT NULL
        REFERENCES words(word_id) ON DELETE CASCADE,

    -- Current learning status
    status VARCHAR(20) NOT NULL DEFAULT 'learning'
        CHECK (status IN ('learning', 'learned')),

    -- How the word was marked as learned
    source VARCHAR(20) NOT NULL DEFAULT 'manual'
        CHECK (source IN ('manual', 'quiz', 'both')),

    -- Number of times the word was reviewed
    review_count INTEGER NOT NULL DEFAULT 0
        CHECK (review_count >= 0),

    -- Correct answers linked to this word
    correct_count INTEGER NOT NULL DEFAULT 0
        CHECK (correct_count >= 0),

    -- Whether the user manually marked this word learned
    manually_marked_learned BOOLEAN NOT NULL DEFAULT FALSE,

    last_reviewed_at TIMESTAMPTZ,

    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    -- One progress record per user per word
    UNIQUE (user_id, word_id)
);


-- 5. INDEXES
-- Improve common account and progress lookups

CREATE INDEX IF NOT EXISTS idx_quiz_attempts_user
    ON quiz_attempts(user_id);

CREATE INDEX IF NOT EXISTS idx_quiz_attempts_quiz
    ON quiz_attempts(quiz_id);

CREATE INDEX IF NOT EXISTS idx_quiz_attempts_completed
    ON quiz_attempts(user_id, completed_at DESC);

CREATE INDEX IF NOT EXISTS idx_answer_details_attempt
    ON quiz_answer_details(attempt_id);

CREATE INDEX IF NOT EXISTS idx_answer_details_word
    ON quiz_answer_details(word_id);

CREATE INDEX IF NOT EXISTS idx_word_progress_user
    ON user_word_progress(user_id);

CREATE INDEX IF NOT EXISTS idx_word_progress_word
    ON user_word_progress(word_id);


-- 6. AUTO-UPDATE USER TIMESTAMP
-- Updates updated_at whenever a user record changes

CREATE OR REPLACE FUNCTION update_users_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_users_updated_at ON users;

CREATE TRIGGER trg_users_updated_at
BEFORE UPDATE ON users
FOR EACH ROW
EXECUTE FUNCTION update_users_updated_at();

SELECT setval(pg_get_serial_sequence('categories', 'category_id'), COALESCE((SELECT MAX(category_id) FROM categories), 1), (SELECT COUNT(*) > 0 FROM categories));
SELECT setval(pg_get_serial_sequence('dialect', 'dialect_id'), COALESCE((SELECT MAX(dialect_id) FROM dialect), 1), (SELECT COUNT(*) > 0 FROM dialect));
SELECT setval(pg_get_serial_sequence('quizzes', 'quiz_id'), COALESCE((SELECT MAX(quiz_id) FROM quizzes), 1), (SELECT COUNT(*) > 0 FROM quizzes));
SELECT setval(pg_get_serial_sequence('words', 'word_id'), COALESCE((SELECT MAX(word_id) FROM words), 1), (SELECT COUNT(*) > 0 FROM words));
SELECT setval(pg_get_serial_sequence('matching_pairs', 'pair_id'), COALESCE((SELECT MAX(pair_id) FROM matching_pairs), 1), (SELECT COUNT(*) > 0 FROM matching_pairs));
SELECT setval(pg_get_serial_sequence('questions', 'question_id'), COALESCE((SELECT MAX(question_id) FROM questions), 1), (SELECT COUNT(*) > 0 FROM questions));
SELECT setval(pg_get_serial_sequence('options', 'option_id'), COALESCE((SELECT MAX(option_id) FROM options), 1), (SELECT COUNT(*) > 0 FROM options));

COMMIT;
