BEGIN;

CREATE TABLE categories (category_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, category_name VARCHAR(100) NOT NULL UNIQUE);
CREATE TABLE dialect (dialect_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, dialect_name VARCHAR(100) NOT NULL UNIQUE);
CREATE TABLE quizzes (quiz_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, dialect_id INTEGER NOT NULL, game_type VARCHAR(50) NOT NULL, title VARCHAR(255) NOT NULL, CONSTRAINT fk_quizzes_dialect FOREIGN KEY (dialect_id) REFERENCES dialect(dialect_id) ON DELETE CASCADE);
CREATE TABLE words (word_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, dialect_id INTEGER NOT NULL, category_id INTEGER NOT NULL, word VARCHAR(255) NOT NULL, pronunciation VARCHAR(255), tagalog VARCHAR(255), english VARCHAR(255), example TEXT, image_path VARCHAR(500), audio_path VARCHAR(500), CONSTRAINT fk_words_category FOREIGN KEY (category_id) REFERENCES categories(category_id) ON DELETE CASCADE, CONSTRAINT fk_words_dialect FOREIGN KEY (dialect_id) REFERENCES dialect(dialect_id) ON DELETE CASCADE);
CREATE TABLE matching_pairs (pair_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, quiz_id INTEGER NOT NULL, word_id INTEGER NOT NULL, match_text VARCHAR(255) NOT NULL, CONSTRAINT fk_matching_quiz FOREIGN KEY (quiz_id) REFERENCES quizzes(quiz_id) ON DELETE CASCADE, CONSTRAINT fk_matching_word FOREIGN KEY (word_id) REFERENCES words(word_id) ON DELETE CASCADE);
CREATE TABLE questions (question_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, quiz_id INTEGER NOT NULL, word_id INTEGER NOT NULL, question_text TEXT NOT NULL, hint VARCHAR(255), CONSTRAINT fk_questions_quiz FOREIGN KEY (quiz_id) REFERENCES quizzes(quiz_id) ON DELETE CASCADE, CONSTRAINT fk_questions_word FOREIGN KEY (word_id) REFERENCES words(word_id) ON DELETE CASCADE);
CREATE TABLE options (option_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, question_id INTEGER NOT NULL, option_text VARCHAR(255) NOT NULL, is_correct SMALLINT NOT NULL DEFAULT 0 CHECK (is_correct IN (0, 1)), CONSTRAINT fk_options_question FOREIGN KEY (question_id) REFERENCES questions(question_id) ON DELETE CASCADE);

